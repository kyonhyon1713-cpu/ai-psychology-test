// 두 성향의 순서가 바뀌어도 같은 결과를 찾도록 정렬
export function getResultTypeProfile(
  topTraits: readonly [Trait, Trait]
): ResultTypeProfile {
  const sortedTraits = [...topTraits].sort(
    (a, b) => traitOrder.indexOf(a) - traitOrder.indexOf(b)
  );

  const key = `${sortedTraits[0]}-${sortedTraits[1]}`;

  const profile = resultTypeProfiles[key];

  if (!profile) {
    throw new Error(`결과 유형을 찾을 수 없습니다: ${key}`);
  }

  return profile;
}